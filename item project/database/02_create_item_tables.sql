CREATE TABLE ITEM_USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(120) NOT NULL,
    PHONE_NUMBER VARCHAR2(20) NOT NULL UNIQUE,
    EMAIL VARCHAR2(120) NOT NULL UNIQUE,
    USER_PASSWORD VARCHAR2(120) NOT NULL,
    IS_ADMIN NUMBER(1) DEFAULT 0 NOT NULL,
    CAN_UPDATE_PRODUCTS NUMBER(1) DEFAULT 0 NOT NULL,
    CAN_DELETE_PRODUCTS NUMBER(1) DEFAULT 0 NOT NULL,
    CAN_UPDATE_CATEGORIES NUMBER(1) DEFAULT 0 NOT NULL,
    CAN_DELETE_CATEGORIES NUMBER(1) DEFAULT 0 NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE CATEGORIES (
    CATEGORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(120) NOT NULL UNIQUE
);

CREATE TABLE PRODUCTS (
    PRODUCT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_NAME VARCHAR2(160) NOT NULL,
    CATEGORY_ID NUMBER NOT NULL,
    PRICE NUMBER(12,2) NOT NULL,
    QUANTITY NUMBER(10) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_PRODUCT_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID),
    CONSTRAINT CHECK_PRODUCT_PRICE CHECK (PRICE >= 0),
    CONSTRAINT CHECK_PRODUCT_QUANTITY CHECK (QUANTITY >= 0)
);

CREATE TABLE PRODUCT_DETAILS (
    PRODUCT_ID NUMBER PRIMARY KEY,
    DESCRIPTION VARCHAR2(1000),
    ISSUE_DATE DATE,
    EXPIRY_DATE DATE,
    CONSTRAINT FK_DETAILS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);
