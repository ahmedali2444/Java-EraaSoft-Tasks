CREATE TABLE WALLET_CARDS (
    CARD_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_ID NUMBER NOT NULL,
    BANK_NAME VARCHAR2(100) NOT NULL,
    CARD_HOLDER_NAME VARCHAR2(120) NOT NULL,
    CARD_FINGERPRINT VARCHAR2(64) NOT NULL,
    LAST_FOUR_DIGITS VARCHAR2(4) NOT NULL,
    EXPIRY_MONTH NUMBER(2) NOT NULL,
    EXPIRY_YEAR NUMBER(4) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_CARD_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
        REFERENCES WALLET_ACCOUNTS(ACCOUNT_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_ACCOUNT_CARD UNIQUE (ACCOUNT_ID, CARD_FINGERPRINT),
    CONSTRAINT CHECK_CARD_MONTH CHECK (EXPIRY_MONTH BETWEEN 1 AND 12)
);
