
CREATE TABLE WALLET_ACCOUNTS (
    ACCOUNT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR2(120) NOT NULL UNIQUE,
    USER_PASSWORD VARCHAR2(100) NOT NULL,
    PHONE_NUMBER VARCHAR2(20) NOT NULL UNIQUE,
    AGE NUMBER(3) NOT NULL,
    BALANCE NUMBER(15, 2) DEFAULT 0 NOT NULL,
    IS_ADMIN NUMBER(1) DEFAULT 0 NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT CHECK_ACCOUNT_AGE CHECK (AGE >= 18),
    CONSTRAINT CHECK_ACCOUNT_BALANCE CHECK (BALANCE >= 0),
    CONSTRAINT CHECK_ACCOUNT_ADMIN CHECK (IS_ADMIN IN (0, 1)),
    CONSTRAINT CHECK_ACCOUNT_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE WALLET_TRANSACTIONS (
    TRANSACTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_ID NUMBER NOT NULL,
    TRANSACTION_TYPE VARCHAR2(30) NOT NULL,
    AMOUNT NUMBER(15, 2) DEFAULT 0 NOT NULL,
    RELATED_EMAIL VARCHAR2(120),
    DESCRIPTION VARCHAR2(500) NOT NULL,
    TRANSACTION_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_TRANSACTION_ACCOUNT
        FOREIGN KEY (ACCOUNT_ID) REFERENCES WALLET_ACCOUNTS(ACCOUNT_ID) ON DELETE CASCADE,
    CONSTRAINT CHECK_TRANSACTION_TYPE CHECK (TRANSACTION_TYPE IN
        ('SIGNUP', 'LOGIN', 'DEPOSIT', 'WITHDRAW', 'TRANSFER_SENT',
         'TRANSFER_RECEIVED', 'PASSWORD_CHANGE', 'ACCOUNT_INACTIVE')),
    CONSTRAINT CHECK_TRANSACTION_AMOUNT CHECK (AMOUNT >= 0)
);
